"""Write outputs/REPORT.md from the pipeline's results (numbers are never hand-typed)."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from ncv.config import OUTPUT_DIR, SALARY_CAP, SETTINGS, season_label


MODEL_NAMES = {"xgboost": "XGBoost, monotonic (chosen)", "ridge_all_features": "Ridge, all features",
               "ridge_simple": "Ridge, 4 core stats"}


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def _m(x: float) -> str:
    if pd.isna(x):
        return ""
    return f"{'−' if x < 0 else ''}${abs(x) / 1e6:,.1f}M"


def _rel(path: str) -> str:
    return str(Path(path).relative_to(OUTPUT_DIR))


def _availability_section(b: pd.DataFrame, cap: float) -> list[str]:
    inj = b[b["injury_shortened"] == 1].sort_values("availability_cost", ascending=False)
    lines = ["**Biggest availability costs** (value lost to missed games, valued at healthy pace)", ""]
    if inj.empty:
        return lines + ["_No injury-shortened rotation seasons this year._", ""]
    t = pd.DataFrame({
        "Player": inj["player"].head(10), "Team": inj["team"].head(10),
        "Games": inj.head(10).apply(lambda r: f"{int(r['g'])}/{int(r['team_games'])}", axis=1),
        "Realized value": (inj["production_value"].head(10) * cap).map(_m),
        "Healthy-pace value": (inj["healthy_value"].head(10) * cap).map(_m),
        "Availability cost": (inj["availability_cost"].head(10) * cap).map(_m),
        "Salary": inj["salary"].head(10).map(_m)})
    return lines + [md_table(t), ""]


def write_report(summary, board, proj, teams, arche, team_views, figs, cur, nxt) -> Path:
    cap, ncap = SALARY_CAP[cur], SALARY_CAP[nxt]
    mk, fc = summary["market"], summary["forecast"]
    b = board[board["salary"].notna() & (board["mp"] >= SETTINGS.min_minutes_value)].copy()

    def board_rows(df):
        return pd.DataFrame({
            "Player": df["player"], "Team": df["team"], "Contract": df["contract_type"],
            "Salary": df["salary"].map(_m), "Market value": (df["market_value"] * cap).map(_m),
            "Realized value": (df["production_value"] * cap).map(_m),
            "Realized surplus": (df["realized_surplus"] * cap).map(_m),
            "Games": df.apply(lambda r: f"{int(r['g'])}/{int(r['team_games'])}"
                              + (" ⚕" if r["injury_shortened"] == 1 else ""), axis=1)})

    vet = b[b["contract_type"] == "Veteran"]
    out = [f"# Results — NBA Contract Value ({season_label(cur)} season, {season_label(nxt)} projections)",
           "", "_Generated by `python -m ncv.pipeline`. Every number below comes from the run._", ""]

    out += ["## Model validation (rolling-origin backtest, "
            f"{summary['seasons_backtested'][0]} to {summary['seasons_backtested'][-1]})", "",
            "Each season is predicted by a model trained only on earlier seasons.", ""]
    out.append(md_table(pd.DataFrame([
        {"Market-value model": MODEL_NAMES.get(n, n), "MAE": _m(v["mae_dollars"]), "R²": f"{v['r2']:.3f}",
         "Rank corr.": f"{v['spearman']:.3f}"}
        for n, v in sorted(mk.items(), key=lambda kv: kv[1]["mae_dollars"])])))
    out += ["", md_table(pd.DataFrame([{
        "Next-season WAR forecast": "Quantile XGBoost (P50)", "MAE (wins)": f"{fc['mae_xgb_p50']:.2f}"},
        {"Next-season WAR forecast": "Marcel-style baseline", "MAE (wins)": f"{fc['mae_marcel']:.2f}"},
        {"Next-season WAR forecast": "Last season carried forward", "MAE (wins)": f"{fc['mae_naive']:.2f}"}])),
        "", f"- P10–P90 interval coverage: **{fc['coverage_p10_p90']:.1%}** (target 80%); "
        f"{fc['below_p10']:.1%} of outcomes fell below P10, {fc['above_p90']:.1%} above P90.",
        ("- Forecast beats Marcel in **every** backtest season." if summary["forecast_beats_marcel_every_season"]
         else "- Forecast does not beat Marcel in every backtest season."),
        f"- Salary join coverage for rotation players: {summary['salary_match_rate']:.1%}.",
        f"- League price of a win in {season_label(cur)}: {_m(summary['usd_per_war_current'])} per WAR.", "",
        f"![]({_rel(figs['market_backtest'])})", "", f"![]({_rel(figs['forecast_backtest'])})", ""]

    out += [f"## {season_label(cur)} value board", "",
            "Realized surplus = what the player's wins were worth at the league's price of a win, "
            "minus salary. It counts availability, so injury-shortened seasons score low.", "",
            "**Biggest veteran-contract bargains**", "", md_table(board_rows(vet.nlargest(10, "realized_surplus"))), "",
            "**Biggest rookie-scale bargains**", "",
            md_table(board_rows(b[b["contract_type"] == "Rookie scale"].nlargest(10, "realized_surplus"))), "",
            "**Largest shortfalls**", "", md_table(board_rows(b.nsmallest(10, "realized_surplus"))), "",
            "_⚕ = injury-shortened: played under "
            f"{SETTINGS.injury_games_pct:.0%} of his team's games at a rotation pace (or was a 1,000+ minute "
            "player the year before). It means he missed most of the season, not that an injury was "
            "confirmed._", "",
            *_availability_section(b, cap),
            f"![]({_rel(figs['scatter'])})", "", f"![]({_rel(figs['leaders'])})", ""]

    out += ["## Team efficiency", "",
            f"Correlation of team realized surplus with wins: **{summary['team_surplus_win_corr']:.2f}**; "
            f"of team WAR with wins: **{summary['team_war_win_corr']:.2f}** (a check that the value scale "
            "tracks winning).", "",
            md_table(pd.DataFrame({"Team": teams["team"], "Wins": teams["w"].astype("Int64"),
                                   "Tracked payroll": teams["payroll_tracked"].map(_m),
                                   "WAR": teams["war"].round(1),
                                   "Realized surplus": (teams["realized_surplus"] * cap).map(_m),
                                   "Payroll per WAR": teams["usd_per_war"].map(_m)})), "",
            f"![]({_rel(figs['teams'])})", ""]

    out += ["## Which roles the market misprices", "",
            "Gap between realized production value and the out-of-sample market price, veterans with "
            f"{SETTINGS.min_minutes_value}+ minutes, all backtest seasons. Positive = the market under-prices that role's output. "
            "Caveat: production value is box-score based (VORP), which tends to credit on-ball and "
            "rim roles more than off-ball shooting and defense.", "",
            md_table(pd.DataFrame({"Archetype": arche["archetype"], "Player-seasons": arche["n"],
                                   "Mean gap (% cap)": (arche["mean_gap_pct_cap"] * 100).round(2),
                                   "90% CI": [f"[{lo * 100:.2f}, {hi * 100:.2f}]"
                                              for lo, hi in zip(arche["ci_low"], arche["ci_high"])],
                                   f"{season_label(cur)} examples": arche["example_players_2026"]})), "",
            f"![]({_rel(figs['archetypes'])})", ""]

    out += [f"## {season_label(nxt)} projections", "",
            "Value of the P10/P50/P90 WAR forecast at the recent league price of a win, compared "
            f"with actual {season_label(nxt)} salaries (Spotrac snapshot) where available. Teams are "
            "current rosters from the same snapshot.", ""]
    top = proj[proj["surplus_p50"].notna()].nlargest(15, "surplus_p50")
    out += ["**Highest projected surplus (P50)**", "", md_table(pd.DataFrame({
        "Player": top["player"], "Team": top["team"], "Salary": (top["pct_cap"] * ncap).map(_m), "Age": top["age"].astype(int),
        "WAR P10/P50/P90": [f"{a:.1f} / {m:.1f} / {c:.1f}" for a, m, c in
                            zip(top["war_p10"], top["war_p50"], top["war_p90"])],
        "Projected value (P50)": (top["value_p50"] * ncap).map(_m),
        "Surplus P10 / P50": [f"{_m(a * ncap)} / {_m(m * ncap)}" for a, m in
                              zip(top["surplus_p10"], top["surplus_p50"])]})), ""]

    for team, v in team_views.items():
        p = v["projection"]
        out += [f"### {team} {season_label(nxt)} roster", "",
                (f"Too few NBA minutes for a projection (rookies, two-way and deep-bench players): "
                 f"{', '.join(v['no_history'])}."
                 if v["no_history"] else ""), "",
                md_table(pd.DataFrame({
                    "Player": p["player"], "Age": p["age"].astype(int), "Archetype": p["archetype"].fillna("—"),
                    "WAR P10 / P50 / P90": [f"{a:.1f} / {m:.1f} / {c:.1f}" for a, m, c in
                                            zip(p["war_p10"], p["war_p50"], p["war_p90"])],
                    "Value (P50)": (p["value_p50"] * ncap).map(_m),
                    "Salary": (p["pct_cap"] * ncap).map(_m),
                    "Surplus (P50)": (p["surplus_p50"] * ncap).map(_m),
                    "Market value": (p["market_value"] * ncap).map(_m),
                    "Top drivers of market value": p["drivers"]})), ""]
        if f"projection_{team}" in figs:
            out += [f"![]({_rel(figs[f'projection_{team}'])})", ""]

    path = OUTPUT_DIR / "REPORT.md"
    path.write_text("\n".join(out))
    return path
